-- Accès : chacun voit sa propre ligne ; l'admin gère tout, sauf se retirer lui-même
create policy "lecture"      on public.acces for select to authenticated using (discord_id = public.discord_id() or public.a_le_role('admin'));
create policy "ajout"        on public.acces for insert to authenticated with check (public.a_le_role('admin'));
