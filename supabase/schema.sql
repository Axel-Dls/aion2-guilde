-- Ivalys · base Supabase
--
-- À coller UNE fois dans Supabase → SQL Editor → « Run ».
-- Le script peut être relancé sans risque : il ne supprime aucune donnée.
--
-- Qui voit quoi (vérifié par la base elle-même, « Row Level Security ») :
--   admin   : tout, plus la gestion des accès
--   gerant  : classement, liste des membres et évaluations (lecture et écriture)
--   lecteur : classement seulement (lecture)
--   personne d'autre : rien, même avec la clé publique du site
--
-- On se connecte avec Discord. L'identifiant Discord (provider_id) est lu dans
-- auth.identities, que l'utilisateur ne peut pas modifier.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------

-- Comptes Discord autorisés et leur rôle
create table if not exists public.acces (
  discord_id  text primary key,
  pseudo      text not null,                 -- nom affiché (souvent le pseudo en jeu)
  role        text not null check (role in ('admin', 'gerant', 'lecteur')),
  ajoute_le   timestamptz not null default now()
);

-- Personnes connectées avec Discord mais pas encore autorisées
create table if not exists public.demandes_acces (
  discord_id   text primary key,
  nom_discord  text,
  avatar       text,
  demande_le   timestamptz not null default now()
);

-- Persos suivis (ou en attente) et leurs dernières valeurs relevées
create table if not exists public.membres (
  id            bigint generated by default as identity primary key,
  pseudo        text not null check (length(trim(pseudo)) > 0),
  serveur       text not null default 'Triniel',
  statut        text not null default 'Membre' check (statut in ('Chef', 'Officier', 'Membre')),
  main          text not null default '',       -- vide pour un perso principal, sinon le pseudo de son main
  suivi         boolean not null default true,  -- false = « en attente »
  anciens_noms  text[] not null default '{}',   -- pour retrouver l'historique d'un perso renommé
  -- Rempli par le relevé automatique
  classe        text,
  niveau        int,
  cp            int,
  gs            int,
  legion        text,
  image         text,
  character_id  text,
  server_id     int,
  region        text,
  etat          text,                           -- ok, not_found, unknown_server, error
  dernier_ok    timestamptz,
  cree_le       timestamptz not null default now(),
  cle           text generated always as (lower(trim(serveur)) || ':' || lower(trim(pseudo))) stored unique
);

-- Un relevé par perso et par jour (historique des GS et CP)
create table if not exists public.releves (
  membre_id  bigint not null references public.membres (id) on delete cascade,
  jour       date not null,
  gs         int,
  cp         int,
  source     text not null default 'site',     -- site (officiel), manuel, jeu (capture)
  primary key (membre_id, jour)
);
create index if not exists releves_jour on public.releves (jour);

-- Passages du relevé automatique (le dernier sert à l'état du suivi)
create table if not exists public.passages (
  id             bigint generated by default as identity primary key,
  debut          timestamptz not null default now(),
  fin            timestamptz,
  ok             int,
  total          int,
  signalements   jsonb not null default '[]',     -- [{name, type, detail}]
  declencheur    text                              -- planifié, demande, manuel, migration
);
create index if not exists passages_debut on public.passages (debut desc);

-- Demandes de relevé (bouton « Relancer », ajout d'un perso…)
create table if not exists public.demandes_maj (
  id          bigint generated by default as identity primary key,
  demande_le  timestamptz not null default now(),
  par         text,
  motif       text
);

-- Évaluations des gérants : une fiche par joueur (perso principal)
create table if not exists public.evaluations (
  pseudo_norm  text primary key,                -- pseudo en minuscules
  pseudo       text not null,
  crit         jsonb not null default '{}',     -- {progression: "ok"|"moyen"|"ko", …}
  alerte       boolean not null default false,
  commentaire  text not null default '',
  maj_le       timestamptz not null default now(),
  maj_par      text
);

-- Réglages de la guilde (nom, région)
create table if not exists public.reglages (
  cle     text primary key,
  valeur  text not null
);
insert into public.reglages (cle, valeur) values ('guilde', 'Ivalys'), ('region', 'eu')
on conflict (cle) do nothing;


-- -----------------------------------------------------------------------------
-- Qui est connecté, avec quel rôle
-- -----------------------------------------------------------------------------

-- Identifiant Discord du compte connecté (null si pas connecté avec Discord)
create or replace function public.discord_id()
returns text language sql stable security definer set search_path = '' as $$
  select i.provider_id from auth.identities i
  where i.user_id = auth.uid() and i.provider = 'discord'
  limit 1
$$;

-- Rôle du compte connecté (null s'il n'est pas autorisé)
create or replace function public.mon_role()
returns text language sql stable security definer set search_path = '' as $$
  select a.role from public.acces a where a.discord_id = public.discord_id()
$$;

create or replace function public.a_le_role(variadic roles text[])
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.mon_role() = any (roles), false)
$$;

-- Appelée par le site à chaque connexion : renvoie le rôle et, si le compte
-- n'est pas autorisé, l'inscrit dans les demandes d'accès.
create or replace function public.mon_acces()
returns json language plpgsql volatile security definer set search_path = '' as $$
declare
  did   text := public.discord_id();
  r     text;
  infos jsonb;
begin
  if did is null then
    return json_build_object('discord_id', null, 'role', null);
  end if;
  select a.role into r from public.acces a where a.discord_id = did;
  select i.identity_data into infos from auth.identities i
    where i.user_id = auth.uid() and i.provider = 'discord' limit 1;
  if r is null then
    insert into public.demandes_acces (discord_id, nom_discord, avatar)
    values (did,
            coalesce(infos #>> '{custom_claims,global_name}', infos ->> 'full_name', infos ->> 'name'),
            infos ->> 'avatar_url')
    on conflict (discord_id) do update
      set nom_discord = excluded.nom_discord, avatar = excluded.avatar;
  end if;
  return json_build_object(
    'discord_id', did,
    'role', r,
    -- vrai tant qu'aucun admin n'existe : le site montre alors comment devenir le premier
    'premier_admin', not exists (select 1 from public.acces a where a.role = 'admin'),
    'nom', coalesce(infos #>> '{custom_claims,global_name}', infos ->> 'full_name', infos ->> 'name'),
    'avatar', infos ->> 'avatar_url');
end
$$;

-- Ajouter un perso ou changer sa liste de suivi demande un nouveau relevé
create or replace function public.demander_releve_auto()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT'
     or new.pseudo is distinct from old.pseudo
     or new.serveur is distinct from old.serveur
     or (new.suivi and not old.suivi) then
    insert into public.demandes_maj (par, motif)
    values (coalesce((select a.pseudo from public.acces a where a.discord_id = public.discord_id()), 'site'),
            'liste des membres modifiée');
  end if;
  return new;
end
$$;
drop trigger if exists membres_demande_releve on public.membres;
create trigger membres_demande_releve
  after insert or update on public.membres
  for each row execute function public.demander_releve_auto();

-- « Qui » et « quand » sont écrits par la base, pas par le navigateur (impossible à falsifier).
-- Le relevé automatique (clé secrète, sans compte Discord) garde ce qu'il envoie.
create or replace function public.signer_modification()
returns trigger language plpgsql security definer set search_path = '' as $$
declare qui text := (select a.pseudo from public.acces a where a.discord_id = public.discord_id());
begin
  if public.discord_id() is null then
    return new;
  end if;
  if tg_table_name = 'evaluations' then
    new.maj_par := coalesce(qui, public.discord_id());
    new.maj_le := now();
  elsif tg_table_name = 'demandes_maj' then
    new.par := coalesce(qui, public.discord_id());
    new.demande_le := now();
  end if;
  return new;
end
$$;
drop trigger if exists evaluations_signature on public.evaluations;
create trigger evaluations_signature before insert or update on public.evaluations
  for each row execute function public.signer_modification();
drop trigger if exists demandes_maj_signature on public.demandes_maj;
create trigger demandes_maj_signature before insert on public.demandes_maj
  for each row execute function public.signer_modification();


-- -----------------------------------------------------------------------------
-- Droits : rien pour les visiteurs anonymes, tout passe par les règles ci-dessous
-- (le relevé automatique utilise la clé secrète, qui n'est pas concernée)
-- -----------------------------------------------------------------------------

revoke all on public.acces, public.demandes_acces, public.membres, public.releves, public.passages,
              public.demandes_maj, public.evaluations, public.reglages from anon, authenticated;

-- Clé secrète (relevé automatique, migration) : tout, sans les règles
grant all on public.acces, public.demandes_acces, public.membres, public.releves, public.passages,
             public.demandes_maj, public.evaluations, public.reglages to service_role;
grant usage, select on all sequences in schema public to service_role;

grant select, insert, update, delete on public.acces          to authenticated;
grant select, delete                 on public.demandes_acces to authenticated;
-- Membres : les gérants ne touchent qu'à la liste (pseudo, serveur, statut, alt, suivi).
-- GS, CP, classe… ne sont écrits que par le relevé automatique.
grant select, delete                 on public.membres        to authenticated;
grant insert (pseudo, serveur, statut, main, suivi, anciens_noms) on public.membres to authenticated;
grant update (pseudo, serveur, statut, main, suivi, anciens_noms) on public.membres to authenticated;
grant select                         on public.releves        to authenticated;
grant select                         on public.passages       to authenticated;
grant select, insert                 on public.demandes_maj   to authenticated;
grant select, insert, update, delete on public.evaluations    to authenticated;
grant select                         on public.reglages       to authenticated;

revoke execute on function public.discord_id(), public.mon_role(), public.a_le_role(text[]),
                           public.mon_acces(), public.demander_releve_auto(), public.signer_modification() from public, anon, authenticated;
grant execute on function public.mon_acces() to authenticated;
grant execute on function public.discord_id(), public.mon_role(), public.a_le_role(text[]) to authenticated;

alter table public.acces          enable row level security;
alter table public.demandes_acces enable row level security;
alter table public.membres        enable row level security;
alter table public.releves        enable row level security;
alter table public.passages       enable row level security;
alter table public.demandes_maj   enable row level security;
alter table public.evaluations    enable row level security;
alter table public.reglages       enable row level security;

-- Les règles sont recréées à chaque lancement du script
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
           where schemaname = 'public'
             and tablename in ('acces', 'demandes_acces', 'membres', 'releves', 'passages',
                               'demandes_maj', 'evaluations', 'reglages')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end
$$;

-- Lecture du classement : tous les comptes autorisés
create policy "lecture" on public.membres  for select to authenticated using (public.a_le_role('admin', 'gerant', 'lecteur'));
create policy "lecture" on public.releves  for select to authenticated using (public.a_le_role('admin', 'gerant', 'lecteur'));
create policy "lecture" on public.passages for select to authenticated using (public.a_le_role('admin', 'gerant', 'lecteur'));
create policy "lecture" on public.reglages for select to authenticated using (public.a_le_role('admin', 'gerant', 'lecteur'));

-- Gestion des membres : gérants et admin
create policy "ajout"        on public.membres for insert to authenticated with check (public.a_le_role('admin', 'gerant'));
create policy "modification" on public.membres for update to authenticated using (public.a_le_role('admin', 'gerant')) with check (public.a_le_role('admin', 'gerant'));
create policy "suppression"  on public.membres for delete to authenticated using (public.a_le_role('admin', 'gerant'));

-- Demandes de relevé : gérants et admin
create policy "lecture" on public.demandes_maj for select to authenticated using (public.a_le_role('admin', 'gerant'));
create policy "ajout"   on public.demandes_maj for insert to authenticated with check (public.a_le_role('admin', 'gerant'));

-- Évaluations : gérants et admin seulement (pas les lecteurs)
create policy "lecture"      on public.evaluations for select to authenticated using (public.a_le_role('admin', 'gerant'));
create policy "ajout"        on public.evaluations for insert to authenticated with check (public.a_le_role('admin', 'gerant'));
create policy "modification" on public.evaluations for update to authenticated using (public.a_le_role('admin', 'gerant')) with check (public.a_le_role('admin', 'gerant'));
create policy "suppression"  on public.evaluations for delete to authenticated using (public.a_le_role('admin', 'gerant'));

-- Accès : chacun voit sa propre ligne ; l'admin gère tout, sauf se retirer lui-même
create policy "lecture"      on public.acces for select to authenticated using (discord_id = public.discord_id() or public.a_le_role('admin'));
create policy "ajout"        on public.acces for insert to authenticated with check (public.a_le_role('admin'));
create policy "modification" on public.acces for update to authenticated
  using (public.a_le_role('admin') and discord_id <> public.discord_id())
  with check (public.a_le_role('admin'));
create policy "suppression"  on public.acces for delete to authenticated using (public.a_le_role('admin') and discord_id <> public.discord_id());

create policy "lecture"     on public.demandes_acces for select to authenticated using (public.a_le_role('admin'));
create policy "suppression" on public.demandes_acces for delete to authenticated using (public.a_le_role('admin'));
