  using (public.a_le_role('admin') and discord_id <> public.discord_id())
  with check (public.a_le_role('admin'));
create policy "suppression"  on public.acces for delete to authenticated using (public.a_le_role('admin') and discord_id <> public.discord_id());

create policy "lecture"     on public.demandes_acces for select to authenticated using (public.a_le_role('admin'));
create policy "suppression" on public.demandes_acces for delete to authenticated using (public.a_le_role('admin'));
