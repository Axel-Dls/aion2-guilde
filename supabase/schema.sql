-- =============================================================================
-- Ivalys · base Supabase
--
-- À coller UNE fois dans Supabase → SQL Editor → « Run ».
-- Le script peut être relancé sans risque : il ne supprime aucune donnée.
--
-- Qui voit quoi (vérifié par la base elle-même, « Row Level Security ») :
--   admin   : tout, plus la gestion des accès
--   gerant  : classement, liste des membres et évaluations (lecture et écriture)
--   lecteur : classement seulement (lecture)
--   personne d'autre : rien, même avec la clé publique du site
--
-- On se connecte avec Discord. L'identifiant Discord (provider_id) est lu dans
-- auth.identities, que l'utilisateur ne peut pas modifier.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------

-- Comptes Discord autorisés et leur rôle
create table if not exists public.acces (
  discord_id  text primary key,
  pseudo      text not null,                 -- nom affiché (souvent le pseudo en jeu)
  role        text not null check (role in ('admin', 'gerant', 'lecteur')),
  ajoute_le   timestamptz not null default now()
);

-- Personnes connectées avec Discord mais pas encore autorisées
create table if not exists public.demandes_acces (
  discord_id   text primary key,
  nom_discord  text,
  avatar       text,
  demande_le   timestamptz not null default now()
);

-- Persos suivis (ou en attente) et leurs dernières valeurs relevées
create table if not exists public.membres (
  id            bigint generated by default as identity primary key,
  pseudo        text not null check (length(trim(pseudo)) > 0),
  serveur       text not null default 'Triniel',
  statut        text not null default 'Membre' check (statut in ('Chef', 'Officier', 'Membre')),
  main          text not null default '',       -- vide pour un perso principal, sinon le pseudo de son main
  suivi         boolean not null default true,  -- false = « en attente »
  anciens_noms  text[] not null default '{}',   -- pour retrouver l'historique d'un perso renommé
  -- Rempli par le relevé automatique
  classe        text,
  niveau        int,
  cp            int,
  gs            int,
  legion        text,
  image         text,
  character_id  text,
  server_id     int,
  region        text,
  etat          text,                           -- ok, not_found, unknown_server, error
  dernier_ok    timestamptz,
  cree_le       timestamptz not null default now(),
  cle           text generated always as (lower(trim(serveur)) || ':' || lower(trim(pseudo))) stored unique
);

-- Ajouts après la première version (sans effet si déjà là)
alter table public.membres add column if not exists derniere_connexion timestamptz;  -- lue dans la capture du jeu

-- Un relevé par perso et par jour (historique des GS et CP)
create table if not exists public.releves (
  membre_id  bigint not null references public.membres (id) on delete cascade,
  jour       date not null,
  gs         int,
  cp         int,
  source     text not null default 'site',     -- site (officiel), manuel, jeu (capture)
  primary key (membre_id, jour)
);
create index if not exists releves_jour on public.releves (jour);

-- Passages du relevé automatique (le dernier sert à l'état du suivi)
create table if not exists public.passages (
  id             bigint generated by default as identity primary key,
  debut          timestamptz not null default now(),
  fin            timestamptz,
  ok             int,
  total          int,
  signalements   jsonb not null default '[]',     -- [{name, type, detail}]
  declencheur    text                              -- planifié, demande, manuel, migration
);
create index if not exists passages_debut on public.passages (debut desc);

-- Demandes de relevé (bouton « Relancer », ajout d'un perso…)
create table if not exists public.demandes_maj (
  id          bigint generated by default as identity primary key,
  demande_le  timestamptz not null default now(),
  par         text,
  motif       text
);

-- Évaluations des gérants : une fiche par joueur (perso principal)
create table if not exists public.evaluations (
  pseudo_norm  text primary key,                -- pseudo en minuscules
  pseudo       text not null,
  crit         jsonb not null default '{}',     -- {progression: "ok"|"moyen"|"ko", …}
  alerte       boolean not null default false,
  commentaire  text not null default '',
  maj_le       timestamptz not null default now(),
  maj_par      text
);

-- Réglages de la guilde (nom, région)
create table if not exists public.reglages (
  cle     text primary key,
  valeur  text not null
);
insert into public.reglages (cle, valeur) values ('guilde', 'Ivalys'), ('region', 'eu')
on conflict (cle) do nothing;


